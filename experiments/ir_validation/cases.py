"""Small, independently specified acceptance cases for the new event profile.

Expected times are hand-derived from SPEC.md; they are not generated by any
executor. These synthetic cases do not establish spare_mvp compatibility.
"""
from __future__ import annotations

from copy import deepcopy


def model(case_id, *, horizon=20, assets=(), resources=(), work=(), maintenance=(), arrivals=(), domain="aircraft"):
    raw = {
        "schema": "business/v1", "profile": "ir-native-event-v1",
        "model_id": case_id, "revision": "v1", "time_unit": "tick",
        "domain": domain, "horizon": horizon,
        "resources": list(resources), "arrivals": list(arrivals),
    }
    raw.update({("fleet" if domain == "aircraft" else "machines"): list(assets),
                ("missions" if domain == "aircraft" else "jobs"): list(work),
                ("maintenance" if domain == "aircraft" else "outages"): list(maintenance)})
    return raw


def job(id, duration=1, *, release=0, eligible=(), needs=None, after=(), repeat_delay=None):
    out = {"id": id, "release": release, "duration": [duration, duration] if isinstance(duration, int) else list(duration),
           "eligible": list(eligible), "needs": needs or {}, "after": list(after)}
    if repeat_delay is not None:
        out["repeat_delay"] = repeat_delay
    return out


def repair(id, asset, at, duration=1, *, needs=None, repeat_every=None):
    out = {"id": id, "asset": asset, "at": at,
           "duration": [duration, duration] if isinstance(duration, int) else list(duration), "needs": needs or {}}
    if repeat_every is not None:
        out["repeat_every"] = repeat_every
    return out


def resource(id, initial=1, kind="capacity"):
    return {"id": id, "kind": kind, "initial": initial}


def expected(status, start=-1, finish=-1, selected=None, completed=None, generation=None):
    value = {"status": status, "started": start, "finished": finish, "selected_id": selected}
    if completed is not None:
        value["completed"] = completed
    if generation is not None:
        value["generation"] = generation
    return value


def make_cases():
    cases = []

    def add(id, description, raw, processes, *, final_resources=None, final_assets=None, trace_contains=(), trace_absent=(), trace_order=()):
        cases.append({"id": id, "description": description, "business": raw,
                      "expected": {"processes": processes, "resources": final_resources or {},
                                   "assets": final_assets or {}, "trace_contains": list(trace_contains),
                                   "trace_absent": list(trace_absent), "trace_order": list(trace_order)}})

    a = [{"id": "A0"}, {"id": "A1"}]
    add("C01_runtime_spare", "A0 fails before dispatch; the same precompiled candidate list selects A1 at runtime.",
        model("C01", assets=a, work=[job("flight", 2, release=1, eligible=["A0", "A1"])],
              maintenance=[repair("failure", "A0", 0, 4)]),
        {"flight": expected(3, 1, 3, "A1"), "restore:failure": expected(3, 0, 4, "A0")},
        final_assets={"A0": 0, "A1": 0})

    add("C02_capacity_fair_order", "Three simultaneous requests share one capacity unit; declared process order determines starts 0, 3, 5.",
        model("C02", resources=[resource("crew")], work=[job("first", 3, needs={"crew": 1}), job("second", 2, needs={"crew": 1}), job("third", 1, needs={"crew": 1})]),
        {"first": expected(3, 0, 3), "second": expected(3, 3, 5), "third": expected(3, 5, 6)}, final_resources={"crew": 1})

    add("C03_atomic_capacity", "Blocked A+B work acquires neither unit; independent A work starts immediately, avoiding partial holding.",
        model("C03", resources=[resource("A"), resource("B")], work=[job("holder", 2, needs={"B": 1}), job("both", 3, needs={"A": 1, "B": 1}), job("independent", 1, needs={"A": 1})]),
        {"holder": expected(3, 0, 2), "both": expected(3, 2, 5), "independent": expected(3, 0, 1)}, final_resources={"A": 1, "B": 1})

    add("C04_stock_arrival", "Two jobs blocked on empty stock start at arrival tick 3; consumed stock never returns at completion.",
        model("C04", resources=[resource("spare", 0, "stock"), resource("unrelated", 0, "stock")],
              work=[job("one", 2, needs={"spare": 1}), job("two", 4, needs={"spare": 1})],
              arrivals=[{"id": "irrelevant", "time": 1, "resource": "unrelated", "quantity": 1}, {"id": "delivery", "time": 3, "resource": "spare", "quantity": 2}]),
        {"one": expected(3, 3, 5), "two": expected(3, 3, 7)}, final_resources={"spare": 0, "unrelated": 1})

    add("C05_same_tick_failure_first", "The prequeued failure at tick 2 precedes the dynamically queued completion at tick 2, so flight aborts.",
        model("C05", assets=[{"id": "A"}], work=[job("flight", 2, eligible=["A"])], maintenance=[repair("failure", "A", 2, 1)]),
        {"flight": expected(4, 0, -1, "A", completed=0), "restore:failure": expected(3, 2, 3, "A")},
        trace_contains=[[2, "abort", "flight", "A", 0]], trace_absent=[[2, "complete", "flight", "A", 0]])

    add("C06_abort_stale_completion", "Aborting releases capacity but consumes stock; an old completion at tick 10 must not change the recovered asset or later job.",
        model("C06", horizon=12, assets=[{"id": "A"}], resources=[resource("crew"), resource("fuel", 1, "stock")],
              work=[job("interrupted", 10, eligible=["A"], needs={"crew": 1, "fuel": 1}), job("later", 2, release=6, eligible=["A"], needs={"crew": 1})],
              maintenance=[repair("fault", "A", 2, 3, needs={"crew": 1})]),
        {"interrupted": expected(4, 0, -1, "A", completed=0), "later": expected(3, 6, 8, "A"), "restore:fault": expected(3, 2, 5, "A")},
        final_resources={"crew": 1, "fuel": 0}, final_assets={"A": 0}, trace_absent=[[10, "complete", "interrupted", "A", 0]])

    add("C07_lifecycle_recurrence", "One recurring mission and one recurring failure reuse fixed process tables across four flights and three repairs.",
        model("C07", horizon=13, assets=[{"id": "A"}], work=[job("flight", 1, eligible=["A"], repeat_delay=3)],
              maintenance=[repair("fault", "A", 2, 1, repeat_every=4)]),
        {"flight": expected(3, 12, 13, "A", completed=4, generation=3), "restore:fault": expected(3, 10, 11, "A", completed=3, generation=2)},
        final_assets={"A": 0}, trace_contains=[[4, "start", "flight", "A", 1], [8, "start", "flight", "A", 1], [10, "start", "restore:fault", "A", 1]])

    add("C08_serial_process_dag", "Explicit serial predecessor edges make durations 2+3+1 complete at tick 6.",
        model("C08", work=[job("cut", 2), job("paint", 3, after=["cut"]), job("dry", 1, after=["paint"])]),
        {"cut": expected(3, 0, 2), "paint": expected(3, 2, 5), "dry": expected(3, 5, 6)})

    add("C09_parallel_process_dag", "Two independent branches run simultaneously; the join waits for both and finishes at max(2,3)+1=4.",
        model("C09", work=[job("cut", 2), job("paint", 3), job("join", 1, after=["cut", "paint"])]),
        {"cut": expected(3, 0, 2), "paint": expected(3, 0, 3), "join": expected(3, 3, 4)})

    add("C10_inclusive_horizon", "Events at tick 5 execute, events after 5 do not; in-flight work remains running with no fabricated finish.",
        model("C10", horizon=5, work=[job("before", 2, release=2), job("boundary", 0, release=5), job("future", 1, release=6), job("unfinished", 6)]),
        {"before": expected(3, 2, 4), "boundary": expected(3, 5, 5), "future": expected(0), "unfinished": expected(2, 0)})

    add("C11_noop_state_no_trigger", "Writing disabled to an already-disabled asset emits no restoration trigger; waiting flight stays blocked.",
        model("C11", horizon=3, assets=[{"id": "A", "initial_state": 1}], work=[job("flight", 1, eligible=["A"])], maintenance=[repair("noop", "A", 1, 1)]),
        {"flight": expected(1), "restore:noop": expected(0)}, final_assets={"A": 1})

    add("C12_dependency_release_gate", "Predecessor completion does not bypass a later release time or activate a release=null dependent.",
        model("C12", work=[job("first", 2), job("delayed", 1, release=5, after=["first"]), job("dormant", 1, release=None, after=["first"])]),
        {"first": expected(3, 0, 2), "delayed": expected(3, 5, 6), "dormant": expected(0)})

    add("C13_production_second_domain", "Production machines, operations and outages lower to the same asset/resource/event operations without a scheduler domain branch.",
        model("C13", domain="production", assets=[{"id": "M1"}, {"id": "M2"}], resources=[resource("operator"), resource("tech")],
              work=[job("cut", 2, release=1, eligible=["M1", "M2"], needs={"operator": 1}),
                    job("polish", 3, eligible=["M1", "M2"], needs={"operator": 1}, after=["cut"]),
                    job("pack", 1, needs={"operator": 1}, after=["polish"])],
              maintenance=[repair("outage", "M1", 0, 4, needs={"tech": 1})]),
        {"cut": expected(3, 1, 3, "M2"), "polish": expected(3, 3, 6, "M2"), "pack": expected(3, 6, 7), "restore:outage": expected(3, 0, 4, "M1")},
        final_resources={"operator": 1, "tech": 1}, final_assets={"M1": 0, "M2": 0})

    add("C14_zero_duration_cascade", "Zero-duration dependency cascades terminate at tick zero with each completion counted once.",
        model("C14", horizon=0, work=[job("a", 0), job("b", 0, after=["a"]), job("c", 0, after=["b"])]),
        {"a": expected(3, 0, 0, completed=1), "b": expected(3, 0, 0, completed=1), "c": expected(3, 0, 0, completed=1)})

    add("C15_atomic_stock", "Blocked mixed acquisition must not consume stock: the stock-only job starts at zero and mixed work waits for replenishment.",
        model("C15", resources=[resource("crew"), resource("spare", 1, "stock")],
              work=[job("holder", 2, needs={"crew": 1}), job("mixed", 1, needs={"crew": 1, "spare": 1}), job("stock_only", 1, needs={"spare": 1})],
              arrivals=[{"id": "replenish", "time": 3, "resource": "spare", "quantity": 1}]),
        {"holder": expected(3, 0, 2), "mixed": expected(3, 3, 4), "stock_only": expected(3, 0, 1)}, final_resources={"crew": 1, "spare": 0})

    add("C16_same_tick_completion_first", "A repeat failure inserted at tick 1 for tick 2 follows the repair completion already queued at tick 0; restoration completes before refailure.",
        model("C16", horizon=2, assets=[{"id": "A"}], maintenance=[repair("fault", "A", 0, 2, repeat_every=1)]),
        {"restore:fault": expected(2, 2, -1, "A", completed=1, generation=1)}, final_assets={"A": 1},
        trace_order=[[2, "complete", "restore:fault", "A", 0], [2, "state", "fault", "A", 1], [2, "start", "restore:fault", "A", 2]])

    return deepcopy(cases)


def rng_model(*, blocked=False, unrelated=False):
    work = []
    assets = [{"id": "A"}]
    if blocked:
        work.append(job("holder", 3, needs={"crew": 1}))
    if unrelated:
        assets = [{"id": "unrelated"}, {"id": "A"}]
        work.append(job("irrelevant", (1, 9), eligible=["unrelated"]))
    work.append(job("random-job", (1, 9), eligible=["A"], needs={"crew": 1}))
    return model("M01_rng_identity", horizon=30, assets=assets, resources=[resource("crew")], work=work)
