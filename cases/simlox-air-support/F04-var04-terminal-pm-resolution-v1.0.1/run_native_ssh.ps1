  excluded_diagnostic_input = @((Join-Path (Split-Path $case -Parent) 'F04-var04-terminal-pm-resolution-v1.0.0\native-input.json'), 'a5767aacb09d437644551e8762a6fca35e27dab80ced98d05b8aeacc8155a7a9')
