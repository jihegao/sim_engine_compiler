  accepted_parent = @((Join-Path (Split-Path $case -Parent) 'F04-var01-deterministic-43day-v1.0.1\native-input.json'), '7b9dfa927ba85c1260d9cbf6d58bae44914ad039a7b3b87b082e1ed04827cc4d')
  accepted_parent_closure = @((Join-Path (Split-Path $case -Parent) 'F04-var01-deterministic-43day-v1.0.1\runs\f04-var01-repeat-a-v101-ssh-20261004-01\closure.json'), 'b054ac23c12ae181f299882256cc95308ee7b15de38d31a36aa7895c995b1447')
  accepted_parent_signoff = @((Join-Path (Split-Path $case -Parent) 'F04-var01-deterministic-43day-v1.0.1\cli-scope-signoff-2026-10-04.md'), 'f7da8657477092954884dfd17fcf681442fffb37df9b2c9d0eb13d91963a4631')
  accepted_parent_report = @((Join-Path (Split-Path $case -Parent) 'F04-var01-deterministic-43day-v1.0.1\runs\f04-var01-repeat-a-v101-ssh-20261004-01\report-raw.json'), '3762a184cd12824f5335b0ac63e39b7f0f264ec6bea9012bcf86b194873b949a')
