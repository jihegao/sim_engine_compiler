"""Derive bounded C04 probes directly from published C03 v1.0.2 inputs."""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PARENTS = {
    "staffing-2": ("83b454bd145621f36571a87cdf8abcbccc184f07ab8f9ad5f3111651c78881e0"),
    "staffing-1": ("159f5fa91d50afbd0d15840f8f007c62a3775d02d718152004017e20e545b789"),
    "staffing-0": ("50682827a363aeb2cb35f860f78671fffd1ea48fbea655ce664eb2c1e2b19267"),
}
VARIANTS = {
    "crew-before": ("staffing-1", {"OperationProfile": {"DTIM": .51}}),
    "crew-equal": ("staffing-1", {"OperationProfile": {"DTIM": .5}}),
    "crew-after": ("staffing-1", {"OperationProfile": {"DTIM": .49}}),
    "aircraft-missing": ("staffing-2", {"SystemDeployment": {"QTYPS": 1}, "OperationProfile": {"DTIM": .5}}),
    "crew-zero": ("staffing-0", {"OperationProfile": {"DTIM": .5}}),
    "horizon-wait": ("staffing-0", {"Control": {"SIMPE": 8.0}, "ResultCollection": {"RCEND": 8.0}}),
}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def rows(table: dict) -> list[dict]:
    names = [column["name"] for column in table["columns"]]
    return [dict(zip(names, row, strict=True)) for row in table["instances"][0]["rows"]]


def build(variant: str) -> tuple[bytes, bytes]:
    parent_name, changes = VARIANTS[variant]
    parent_path = HERE.parent / "C03-shared-crew-formation-v1.0.2" / "inputs" / f"{parent_name}.json"
    source = parent_path.read_bytes()
    if sha(source) != PARENTS[parent_name]:
        raise ValueError(f"published C03 {parent_name} input fingerprint changed")
    parent = json.loads(source)
    child = copy.deepcopy(parent)
    prior = {table["name"]: rows(table) for table in parent["model"]["tables"]}
    for table in child["model"]["tables"]:
        name = table["name"]
        if name not in changes:
            continue
        data = rows(table)
        if not data:
            raise ValueError(f"empty changed table: {name}")
        for record in data:
            for field, value in changes[name].items():
                if field not in record:
                    raise ValueError(f"unknown native field {name}.{field}")
                record[field] = value
        columns = [column["name"] for column in table["columns"]]
        table["instances"][0]["rows"] = [[record[field] for field in columns] for record in data]
    now = {table["name"]: rows(table) for table in child["model"]["tables"]}
    actual = {name for name in prior if prior[name] != now[name]}
    if actual != set(changes):
        raise ValueError(f"unexpected exact table delta: {actual}")
    model = (json.dumps(child, ensure_ascii=False, indent=2) + "\n").encode()
    diff = {"schema": "simlox-c04-exact-parent-diff/v1", "case_id": "C04", "version": "1.0.0",
            "variant_id": variant, "parent_case": f"C03@1.0.2/{parent_name}",
            "parent_input_sha256": PARENTS[parent_name], "child_input_sha256": sha(model),
            "changed_fields": changes, "unchanged_table_count": len(prior) - len(actual),
            "tables": {name: {"parent_rows": prior[name], "child_rows": now[name]} for name in sorted(actual)}}
    return model, (json.dumps(diff, ensure_ascii=False, indent=2) + "\n").encode()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = {}
    for variant in VARIANTS:
        model, diff = build(variant)
        paths = ((HERE / "inputs" / f"{variant}.json", model),
                 (HERE / "parent-diffs" / f"{variant}.json", diff))
        for path, data in paths:
            if args.check:
                if path.read_bytes() != data:
                    raise ValueError(f"generated bytes differ: {path}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
        result[variant] = {"parent": VARIANTS[variant][0], "input_sha256": sha(model),
                           "parent_diff_sha256": sha(diff)}
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
